package main

import (
	"errors"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"syscall"
	"time"
)

const (
	testFastScript      = "test_fast"
	testFullScript      = "test"
	generatedTestScript = "#!/bin/sh\n# Generated by atd init. Replace this stub with the repository's test command.\n# Keep required test setup in project-owned scripts.\n# Full-suite and targeted runs should reuse the same setup.\n# Examples: browser locations, local service settings, or time limits.\n# Keep secrets and machine-specific values out of tracked files.\nprintf '%s\\n' 'atd: replace this generated test stub with the repository test command' >&2\nexit 1\n"
)

func initializeTestScripts(repository string) error {
	scriptDirectory := filepath.Join(repository, "script")
	info, err := os.Lstat(scriptDirectory)
	if errors.Is(err, os.ErrNotExist) {
		if err := os.Mkdir(scriptDirectory, 0o755); err != nil {
			return fmt.Errorf("creating script directory: %w", err)
		}
	} else if err != nil {
		return err
	} else if info.Mode()&os.ModeSymlink != 0 || !info.IsDir() {
		return errors.New("script path must be a non-symlink directory")
	}
	for _, name := range []string{testFastScript, testFullScript} {
		if err := validateTestScript(filepath.Join(scriptDirectory, name)); err != nil {
			return err
		}
	}
	for _, name := range []string{testFastScript, testFullScript} {
		if err := createTestScriptIfMissing(filepath.Join(scriptDirectory, name)); err != nil {
			return err
		}
	}
	return nil
}

func validateTestScript(path string) error {
	info, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	if info.Mode()&os.ModeSymlink != 0 || !info.Mode().IsRegular() {
		return fmt.Errorf("test script %q must be a non-symlink regular file", path)
	}
	if info.Mode().Perm()&0o111 == 0 {
		return fmt.Errorf("test script %q must be executable", path)
	}
	return nil
}

func createTestScriptIfMissing(path string) error {
	file, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o755)
	if err == nil {
		if _, err := file.WriteString(generatedTestScript); err != nil {
			_ = file.Close()
			return fmt.Errorf("writing test script %q: %w", path, err)
		}
		if err := file.Chmod(0o755); err != nil {
			_ = file.Close()
			return fmt.Errorf("making test script %q executable: %w", path, err)
		}
		if err := file.Close(); err != nil {
			return fmt.Errorf("closing test script %q: %w", path, err)
		}
		return nil
	}
	if !errors.Is(err, os.ErrExist) {
		return fmt.Errorf("creating test script %q: %w", path, err)
	}
	return validateTestScript(path)
}

func parseTestCommand(arguments []string) (testMode, []string, error) {
	if len(arguments) == 1 {
		switch arguments[0] {
		case string(testModeFast):
			return testModeFast, []string{"./script/" + testFastScript}, nil
		case string(testModeFull):
			return testModeFull, []string{"./script/" + testFullScript}, nil
		}
	}
	if len(arguments) >= 2 && arguments[0] == "--" {
		return testModeTargeted, append([]string(nil), arguments[1:]...), nil
	}
	return "", nil, errors.New("usage: atd test fast | full | -- <command> [args...]")
}

type testCommandExitError struct {
	status int
	cause  error
}

func (err testCommandExitError) Error() string {
	if err.cause != nil {
		return err.cause.Error()
	}
	return fmt.Sprintf("test command exited with status %d", err.status)
}

func (err testCommandExitError) ExitStatus() int {
	return err.status
}

func runTestCommandWithMode(repository string, mode testMode, arguments []string, stdin io.Reader, stdout, stderr io.Writer) error {
	canonicalRepository, err := filepath.EvalSymlinks(repository)
	if err != nil {
		return fmt.Errorf("canonicalizing repository root: %w", err)
	}
	repository = canonicalRepository
	if len(arguments) == 0 {
		return errors.New("test command must not be empty")
	}
	if err := rejectGeneratedTestStub(repository, mode); err != nil {
		return err
	}
	beforeTree, err := workingTreeID(repository)
	if err != nil {
		return fmt.Errorf("identifying test tree before command: %w", err)
	}
	beforeHead, err := repositoryHeadID(repository)
	if err != nil {
		return fmt.Errorf("identifying HEAD before command: %w", err)
	}
	testOutput := &lineTrackingWriter{writer: stdout}
	status, launchFailed, runErr := executeTestCommand(repository, arguments, stdin, testOutput, stderr)
	afterTree, treeErr := workingTreeID(repository)
	if treeErr != nil {
		if status != 0 {
			return testCommandExitError{status: status, cause: fmt.Errorf("test command exited with status %d; identifying test tree after command: %w", status, treeErr)}
		}
		return fmt.Errorf("identifying test tree after command: %w", treeErr)
	}
	afterHead, headErr := repositoryHeadID(repository)
	if headErr != nil {
		if status != 0 {
			return testCommandExitError{status: status, cause: fmt.Errorf("test command exited with status %d; identifying HEAD after command: %w", status, headErr)}
		}
		return fmt.Errorf("identifying HEAD after command: %w", headErr)
	}
	observation := testObservation{
		Schema:         testObservationSchema,
		Worktree:       repository,
		BeforeTree:     beforeTree,
		AfterTree:      afterTree,
		SourceChanged:  beforeTree != afterTree,
		BeforeHead:     beforeHead,
		AfterHead:      afterHead,
		HistoryChanged: beforeHead != afterHead,
		Signaled:       testCommandWasSignaled(runErr),
		LaunchFailed:   launchFailed,
		Mode:           mode,
		Command:        append([]string(nil), arguments...),
		ExitStatus:     status,
		ObservedAt:     time.Now().UTC().Format(time.RFC3339Nano),
	}
	redToGreen, err := appendTestObservation(repository, observation)
	if err != nil {
		if status != 0 {
			return testCommandExitError{status: status, cause: fmt.Errorf("test command exited with status %d; recording observation: %w", status, err)}
		}
		return fmt.Errorf("recording test observation: %w", err)
	}
	needsOutputSeparation := testOutput.needsNewline()
	separateOutput := func() {
		if needsOutputSeparation {
			_, _ = fmt.Fprintln(stdout)
			needsOutputSeparation = false
		}
	}
	if redToGreen && !observation.SourceChanged && !observation.HistoryChanged {
		separateOutput()
		_, _ = fmt.Fprintln(stdout, "atd: test is green after red; commit, then refactor with tests green before the next test")
	}
	if credibleRed(observation) {
		separateOutput()
		_, _ = fmt.Fprintln(stdout, "atd: test is red; if this is the intended failure, commit the test before continuing")
	}
	if observation.SourceChanged || observation.HistoryChanged {
		problem := errors.New("test command changed source or history during execution")
		if observation.SourceChanged && !observation.HistoryChanged {
			problem = errors.New("test command changed source during execution")
		}
		if observation.HistoryChanged && !observation.SourceChanged {
			problem = errors.New("test command changed history during execution")
		}
		if status != 0 {
			return testCommandExitError{status: status, cause: fmt.Errorf("test command exited with status %d; %w: %v", status, problem, runErr)}
		}
		return testCommandExitError{status: 1, cause: problem}
	}
	if status != 0 {
		return testCommandExitError{status: status, cause: runErr}
	}
	return runErr
}

func repositoryHeadID(repository string) (string, error) {
	head, err := gitOutput(repository, nil, nil, "rev-parse", "--verify", "--quiet", "HEAD^{commit}")
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(head), nil
}

func rejectGeneratedTestStub(repository string, mode testMode) error {
	var script string
	switch mode {
	case testModeFast:
		script = testFastScript
	case testModeFull:
		script = testFullScript
	default:
		return nil
	}
	path := filepath.Join(repository, "script", script)
	if err := validateTestScript(path); err != nil {
		return err
	}
	contents, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	if string(contents) == generatedTestScript {
		return fmt.Errorf("script/%s is the generated stub; replace it before running atd test %s", script, mode)
	}
	return nil
}

func testCommandWasSignaled(err error) bool {
	var exit *exec.ExitError
	if !errors.As(err, &exit) {
		return false
	}
	wait, ok := exit.Sys().(syscall.WaitStatus)
	return ok && wait.Signaled()
}

type lineTrackingWriter struct {
	writer   io.Writer
	lastByte byte
	wrote    bool
}

func (writer *lineTrackingWriter) Write(contents []byte) (int, error) {
	written, err := writer.writer.Write(contents)
	if written > 0 {
		writer.lastByte = contents[written-1]
		writer.wrote = true
	}
	return written, err
}

func (writer *lineTrackingWriter) needsNewline() bool {
	return writer.wrote && writer.lastByte != '\n'
}

func executeTestCommand(repository string, arguments []string, stdin io.Reader, stdout, stderr io.Writer) (int, bool, error) {
	command := exec.Command(arguments[0], arguments[1:]...)
	command.Dir = repository
	command.Stdin = stdin
	command.Stdout = stdout
	command.Stderr = stderr
	err := command.Run()
	if err == nil {
		return 0, false, nil
	}
	var exit *exec.ExitError
	if errors.As(err, &exit) {
		if status := exit.ExitCode(); status >= 0 {
			return status, false, err
		}
		if wait, ok := exit.Sys().(syscall.WaitStatus); ok && wait.Signaled() {
			return 128 + int(wait.Signal()), false, err
		}
	}
	if errors.Is(err, exec.ErrNotFound) || errors.Is(err, os.ErrNotExist) {
		return 127, true, err
	}
	return 126, true, err
}

func workingTreeID(repository string) (string, error) {
	objectPath, err := gitOutput(repository, nil, nil, "rev-parse", "--git-path", "objects")
	if err != nil {
		return "", err
	}
	objects := strings.TrimSpace(objectPath)
	if !filepath.IsAbs(objects) {
		objects = filepath.Join(repository, objects)
	}
	objects, err = filepath.Abs(objects)
	if err != nil {
		return "", err
	}
	temporary, err := os.MkdirTemp("", "atd-test-tree-")
	if err != nil {
		return "", err
	}
	defer os.RemoveAll(temporary)
	temporaryObjects := filepath.Join(temporary, "objects")
	if err := os.Mkdir(temporaryObjects, 0o700); err != nil {
		return "", err
	}
	environment := gitEnvironment(map[string]string{
		"GIT_ALTERNATE_OBJECT_DIRECTORIES": objects,
		"GIT_INDEX_FILE":                   filepath.Join(temporary, "index"),
		"GIT_OBJECT_DIRECTORY":             temporaryObjects,
	})
	headTree, headErr := gitOutput(repository, nil, nil, "rev-parse", "--verify", "--quiet", "HEAD^{tree}")
	if headErr == nil {
		if _, err := gitOutput(repository, environment, nil, "read-tree", strings.TrimSpace(headTree)); err != nil {
			return "", err
		}
	} else if _, err := gitOutput(repository, environment, nil, "read-tree", "--empty"); err != nil {
		return "", err
	}
	if _, err := gitOutput(repository, environment, nil, "add", "-A", "--", "."); err != nil {
		return "", err
	}
	tree, err := gitOutput(repository, environment, nil, "write-tree")
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(tree), nil
}
