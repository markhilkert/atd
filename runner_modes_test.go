func TestInitCreatesFastAndFullTestScripts(t *testing.T) {
	repository := newTestRunnerRepository(t)

	withTestRunnerDirectory(t, repository)
	if err := runCLI([]string{"init"}, io.Discard); err != nil {
		t.Fatal(err)
	}
	for _, path := range []string{"script/test_fast", "script/test"} {
		contents, err := os.ReadFile(filepath.Join(repository, path))
		if err != nil {
			t.Fatalf("read %s: %v", path, err)
		}
		if !strings.Contains(string(contents), "Generated by atd init") || !strings.Contains(string(contents), "replace this generated test stub") {
			t.Fatalf("%s is not an informative generated stub: %q", path, contents)
		}
		info, err := os.Stat(filepath.Join(repository, path))
		if err != nil {
			t.Fatalf("stat %s: %v", path, err)
		}
		if info.Mode().Perm()&0o111 == 0 {
			t.Fatalf("%s is not executable: mode %o", path, info.Mode().Perm())
		}
	}
}

func TestInitPreservesExistingTestScripts(t *testing.T) {
	repository := newTestRunnerRepository(t)
	scriptDirectory := filepath.Join(repository, "script")
	if err := os.Mkdir(scriptDirectory, 0o755); err != nil {
		t.Fatal(err)
	}
	fast := filepath.Join(scriptDirectory, "test_fast")
	full := filepath.Join(scriptDirectory, "test")
	fastContents := "#!/bin/sh\nexit 17\n"
	fullContents := "#!/bin/sh\nexit 19\n"
	if err := os.WriteFile(fast, []byte(fastContents), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(full, []byte(fullContents), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := initializeTestScripts(repository); err != nil {
		t.Fatal(err)
	}
	for path, want := range map[string]string{fast: fastContents, full: fullContents} {
		contents, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		if string(contents) != want {
			t.Fatalf("%s = %q, want %q", path, contents, want)
		}
	}
}

