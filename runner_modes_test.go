func TestInitRejectsUnsafeScriptPaths(t *testing.T) {
	tests := []struct {
		name  string
		setup func(string) error
	}{
		{name: "script directory symlink", setup: func(repository string) error {
			return os.Symlink(filepath.Join(filepath.Dir(repository), "outside-script"), filepath.Join(repository, "script"))
		}},
		{name: "fast script symlink", setup: func(repository string) error {
			if err := os.Mkdir(filepath.Join(repository, "script"), 0o755); err != nil {
				return err
			}
			return os.Symlink(filepath.Join(filepath.Dir(repository), "outside-fast"), filepath.Join(repository, "script", "test_fast"))
		}},
		{name: "fast script directory", setup: func(repository string) error {
			return os.MkdirAll(filepath.Join(repository, "script", "test_fast"), 0o755)
		}},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			repository := newTestRunnerRepository(t)
			if err := test.setup(repository); err != nil {
				t.Fatal(err)
			}
			if err := initializeTestScripts(repository); err == nil {
				t.Fatal("init succeeded for unsafe script path")
			}
		})
	}
}

func TestTestModesRunRegisteredScripts(t *testing.T) {
	repository := newTestRunnerRepository(t)
	if err := os.Mkdir(filepath.Join(repository, "script"), 0o755); err != nil {
		t.Fatal(err)
	}
	markerDirectory := t.TempDir()
	fast := filepath.Join(repository, "script", "test_fast")
	full := filepath.Join(repository, "script", "test")
	if err := os.WriteFile(fast, []byte("#!/bin/sh\nprintf fast > "+filepath.Join(markerDirectory, "mode")+"\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(full, []byte("#!/bin/sh\nprintf full > "+filepath.Join(markerDirectory, "mode")+"\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	for _, mode := range []string{"fast", "full"} {
		parsedMode, command, err := parseTestCommand([]string{mode})
		if err != nil {
			t.Fatal(err)
		}
		if err := runTestCommandWithMode(repository, parsedMode, command, strings.NewReader(""), io.Discard, io.Discard); err != nil {
			t.Fatalf("test %s: %v", mode, err)
		}
		contents, err := os.ReadFile(filepath.Join(markerDirectory, "mode"))
		if err != nil {
			t.Fatal(err)
		}
		if string(contents) != mode {
			t.Fatalf("mode script wrote %q, want %q", contents, mode)
		}
	}
}

