func TestFullModeDoesNotIssueCommitOrRefactoringAdvisories(t *testing.T) {
	repository := newTestRunnerRepository(t)
	if err := os.Mkdir(filepath.Join(repository, "script"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(repository, "script", "test"), []byte("#!/bin/sh\nprintf full-failure\nexit 7\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(repository, "script", "test_fast"), []byte("#!/bin/sh\nexit 0\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	var output bytes.Buffer
	mode, command, err := parseTestCommand([]string{"full"})
	if err != nil {
		t.Fatal(err)
	}
	if err := runTestCommandWithMode(repository, mode, command, strings.NewReader(""), &output, io.Discard); err == nil {
		t.Fatal("full test unexpectedly passed")
	}
	if output.String() != "full-failure" {
		t.Fatalf("full mode failure output = %q", output.String())
	}
	if err := os.WriteFile(filepath.Join(repository, "script", "test"), []byte("#!/bin/sh\nprintf full-green\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	output.Reset()
	if err := runTestCommandWithMode(repository, mode, command, strings.NewReader(""), &output, io.Discard); err != nil {
		t.Fatal(err)
	}
	if output.String() != "full-green" {
		t.Fatalf("full mode green output = %q", output.String())
	}
}

func TestPreviousObservationMatchesModeExactly(t *testing.T) {
	repository := newTestRunnerRepository(t)
	observation := testObservation{
		Schema:     testObservationSchema,
		Worktree:   repository,
		Mode:       testModeTargeted,
		Command:    []string{"true"},
		ExitStatus: 1,
		ObservedAt: "2026-08-29T00:00:00Z",
	}
	if _, err := appendTestObservation(repository, observation); err != nil {
		t.Fatal(err)
	}
	head := strings.TrimSpace(runTestRunnerGit(t, repository, "rev-parse", testObservationRef))
	if _, found, err := previousTestObservation(repository, head, repository, testModeFast, observation.Command); err != nil || found {
		t.Fatalf("fast match = %t, %v; want false, nil", found, err)
	}
	previous, found, err := previousTestObservation(repository, head, repository, testModeTargeted, observation.Command)
	if err != nil || !found || previous.Mode != testModeTargeted {
		t.Fatalf("targeted match = %#v, %t, %v", previous, found, err)
	}
}

func TestTestRejectsUnknownModeAndRequiresTargetedSeparator(t *testing.T) {
	for _, arguments := range [][]string{{"unknown"}, {"sh", "-c", "true"}} {
		if _, _, err := parseTestCommand(arguments); err == nil {
			t.Fatalf("parseTestCommand(%q) succeeded", arguments)
		}
	}
	mode, command, err := parseTestCommand([]string{"--", "true"})
	if err != nil {
		t.Fatal(err)
	}
	if mode != testModeTargeted || strings.Join(command, "\x00") != "true" {
		t.Fatalf("parsed targeted command = %q, %q", mode, command)
	}
}

func withTestRunnerDirectory(t *testing.T, repository string) {
	t.Helper()
	directory, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	if err := os.Chdir(repository); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.Chdir(directory) })
}
